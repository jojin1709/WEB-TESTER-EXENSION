const Utils = {
  // Copy text to clipboard — works in all extension contexts
  copyToClipboard(text) {
    // Prefer Clipboard API (HTTPS / extension pages)
    if (navigator.clipboard && navigator.clipboard.writeText) {
      return navigator.clipboard.writeText(text).then(() => true).catch(() => {
        return this._fallbackCopy(text);
      });
    }
    return Promise.resolve(this._fallbackCopy(text));
  },

  _fallbackCopy(text) {
    try {
      const el = document.createElement('textarea');
      el.value = text;
      el.style.cssText = 'position:fixed;top:-9999px;left:-9999px;opacity:0';
      document.body.appendChild(el);
      el.focus();
      el.select();
      const ok = document.execCommand('copy');
      document.body.removeChild(el);
      return ok;
    } catch (_) { return false; }
  },

  // Show toast notification
  showToast(message, type = 'success', duration = 2500) {
    let container = document.getElementById('toast-container');
    if (!container) {
      container = document.createElement('div');
      container.id = 'toast-container';
      container.className = 'toast-container';
      document.body.appendChild(container);
    }
    const toast = document.createElement('div');
    toast.className = `toast ${type}`;
    const icon = type === 'success' ? '✓' : '✕';
    const iconEl = document.createElement('span');
    iconEl.textContent = icon;
    const messageEl = document.createElement('span');
    messageEl.textContent = message;
    toast.append(iconEl, messageEl);
    container.appendChild(toast);
    setTimeout(() => {
      toast.style.opacity = '0';
      toast.style.transition = 'opacity 0.3s';
      setTimeout(() => { if (toast.parentNode) toast.remove(); }, 300);
    }, duration);
  },

  // Escape HTML to prevent XSS
  escapeHtml(str) {
    if (typeof str !== 'string') return '';
    return str
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;')
      .replace(/'/g, '&#39;');
  },

  formatDate(ts) {
    if (!ts) return '';
    const d = new Date(ts);
    return d.toLocaleDateString() + ' ' + d.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
  },

  relativeTime(ts) {
    const diff = Date.now() - ts;
    const m = Math.floor(diff / 60000);
    if (m < 1) return 'just now';
    if (m < 60) return `${m}m ago`;
    const h = Math.floor(m / 60);
    if (h < 24) return `${h}h ago`;
    return `${Math.floor(h / 24)}d ago`;
  },

  uid() {
    return Date.now().toString(36) + Math.random().toString(36).slice(2, 7);
  },

  sanitize(str) { return this.escapeHtml(String(str || '')); },

  debounce(fn, delay) {
    let t;
    return (...args) => { clearTimeout(t); t = setTimeout(() => fn(...args), delay); };
  },

  markdownToHtml(md) {
    if (!md) return '';
    let html = this.escapeHtml(md);
    html = html.replace(/```([\s\S]*?)```/g, (_, c) => `<pre class="mono">${c}</pre>`);
    html = html.replace(/`([^`]+)`/g, (_, c) => `<code class="mono">${c}</code>`);
    html = html.replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>');
    html = html.replace(/\*([^*]+)\*/g, '<em>$1</em>');
    html = html.replace(/^### (.+)$/gm, '<h3>$1</h3>');
    html = html.replace(/^## (.+)$/gm, '<h2>$1</h2>');
    html = html.replace(/^# (.+)$/gm, '<h1>$1</h1>');
    html = html.replace(/^\* (.+)$/gm, '<li>$1</li>');
    html = html.replace(/(<li>.*<\/li>)/s, '<ul>$1</ul>');
    html = html.replace(/\[([^\]]+)\]\(([^)]+)\)/g, '<a href="$2" target="_blank" rel="noopener">$1</a>');
    html = html.replace(/\n\n/g, '</p><p>').replace(/\n/g, '<br>');
    return `<p>${html}</p>`;
  },

  truncate(str, len = 80) {
    if (!str) return '';
    return str.length > len ? str.slice(0, len) + '…' : str;
  },

  downloadFile(content, filename, mime = 'text/plain') {
    const blob = new Blob([content], { type: mime });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url; a.download = filename;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  },

  downloadJson(obj, filename) {
    this.downloadFile(JSON.stringify(obj, null, 2), filename, 'application/json');
  },

  readFileAsText(file) {
    return new Promise((resolve, reject) => {
      const reader = new FileReader();
      reader.onload = e => resolve(e.target.result);
      reader.onerror = () => reject(new Error('File read error'));
      reader.readAsText(file);
    });
  },

  validatePayloadPack(data) {
    if (!Array.isArray(data)) return false;
    return data.every(p =>
      typeof p === 'object' && p !== null &&
      typeof p.name === 'string' &&
      typeof p.payload === 'string' &&
      typeof p.category === 'string'
    );
  }
};

// ── Storage helper — uses browserAPI (cross-browser, Promise-based) ──────
const Store = {
  async get(key, fallback = null) {
    if (!browserAPI) return fallback;
    try {
      const result = await browserAPI.storage.local.get(key);
      // Firefox returns {key: value}, Chrome same when promisified
      if (result && key in result) return result[key];
      return fallback;
    } catch (_) { return fallback; }
  },

  async set(key, value) {
    if (!browserAPI) return;
    try { await browserAPI.storage.local.set({ [key]: value }); } catch (_) {}
  },

  async remove(key) {
    if (!browserAPI) return;
    try { await browserAPI.storage.local.remove(key); } catch (_) {}
  },

  async getAll() {
    if (!browserAPI) return {};
    try { return await browserAPI.storage.local.get(null); } catch (_) { return {}; }
  },

  async clear() {
    if (!browserAPI) return;
    try { await browserAPI.storage.local.clear(); } catch (_) {}
  }
};

